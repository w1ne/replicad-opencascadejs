#!/usr/bin/python3
"""Generated OCCT 8 sources the opencascade.js v2 toolchain needs.

1. Standard_Version.hxx: OCCT 8 generates it from adm/templates at CMake time;
   this build compiles OCCT without CMake.
2. src/zzKernelCAD/KCADCompat/KCADCompat_Handles.hxx: OCCT 8 dropped the
   `Handle_<Class>` typedefs (DEFINE_STANDARD_HANDLE) from its headers. The v2
   generator names and binds handle types through those typedefs
   (`Handle_Geom_Curve`, ...), so restore one per transient class. The `zz`
   prefix makes the generator include it after every other OCCT header.

usage: gen-occt8-compat.py /occt
"""
import os
import re
import sys

root = sys.argv[1]
src = os.path.join(root, "src")

# 1. Standard_Version.hxx
template = open(os.path.join(root, "adm/templates/Standard_Version.hxx.in")).read()
version = open(os.path.join(root, "adm/cmake/version.cmake")).read()
for key in ("MAJOR", "MINOR", "MAINTENANCE"):
  value = re.search(r"OCC_VERSION_%s\s+(\d+)" % key, version).group(1)
  template = template.replace("@OCC_VERSION_%s@" % key, value)
template = template.replace("@OCCT_VERSION_DATE@", "2026-01-01").replace("@OCC_VERSION_DATE@", "2026-01-01")
template = template.replace("@SET_OCC_VERSION_DEVELOPMENT@", "")
assert "@" not in re.sub(r"//.*", "", template), "unexpanded Standard_Version.hxx.in placeholder"
open(os.path.join(src, "FoundationClasses/TKernel/Standard/Standard_Version.hxx"), "w").write(template)

# 2. Handle_<Class> typedefs
MODULES = ["FoundationClasses", "ModelingData", "ModelingAlgorithms", "Visualization",
           "ApplicationFramework", "DataExchange"]
SKIP_DIRS = {"GTests", "TKOpenGl", "TKOpenGles", "TKD3DHost", "TKIVtk", "TKMeshVS"}
NOT_CLASSES = {"WNT_WClass"}  # Windows-only
names = set()
for module in MODULES:
  for dirpath, dirnames, filenames in os.walk(os.path.join(src, module)):
    dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
    for f in filenames:
      if not f.endswith(".hxx"):
        continue
      text = open(os.path.join(dirpath, f), errors="replace").read()
      for m in re.finditer(r"^\s*DEFINE_(?:STANDARD_RTTIEXT|STANDARD_RTTI_INLINE|DERIVED_ATTRIBUTE|STANDARD_EXCEPTION|SIMPLE_ALERT|ALERT_WITH_SHAPE)\(\s*(\w+)\s*,", text, re.M):
        name = m.group(1)
        if "_" not in name or name in NOT_CLASSES:
          continue  # macro parameters / documentation examples, not classes
        if re.search(r"template\s*<[^>]*>\s*class\s+" + name + r"\b", text):
          continue
        names.add(name)
out = os.path.join(src, "zzKernelCAD", "KCADCompat")
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "KCADCompat_Handles.hxx"), "w") as f:
  f.write("// Generated by gen-occt8-compat.py: Handle_<Class> typedefs removed in OCCT 8.\n")
  f.write("#ifndef _KCADCompat_Handles_HeaderFile\n#define _KCADCompat_Handles_HeaderFile\n")
  f.write("#include <Standard_Handle.hxx>\n")
  for name in sorted(names):
    f.write("typedef opencascade::handle<%s> Handle_%s;\n" % (name, name))
  f.write("#endif\n")
print("Standard_Version.hxx written; %d Handle_ typedefs" % len(names))
